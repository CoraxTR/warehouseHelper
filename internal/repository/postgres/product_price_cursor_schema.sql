-- Курсор обновителя цен каталога: единственная строка id=1.
--   next_scan_at      — время, с которого сканировать СЛЕДУЮЩИЙ инкремент
--                       каталога МС (что успело измениться). Перезаписывается
--                       СТРОГО после каждого прохода, в том числе при ошибке
--                       запроса (цена — состояние, а не событие: пропущенное
--                       закроет полный проход).
--   last_full_scan_at — МСК-ДАТА последнего ПОЛНОГО прохода по всем id. Именно
--                       по ней решается «сегодня уже сверяли?»: батч привязан к
--                       календарю, а не к интервалу от старта процесса — иначе
--                       рестарты сдвигали бы время прохода всё дальше.
-- Хранится в БД, чтобы рестарт/сон не давали ни пропуска окна, ни дубля.
-- Пишет модуль каталога (goods), читает тот же обновитель.
-- Применить до первого запуска: psql -f product_price_cursor_schema.sql
-- (или DataGrip), аналогично returns_schema.sql.
-- Владелец таблицы — модуль каталога.

DROP TABLE IF EXISTS product_price_cursor;

CREATE TABLE product_price_cursor (
    id                SMALLINT PRIMARY KEY CHECK (id = 1),
    next_scan_at      TIMESTAMPTZ NOT NULL,
    last_full_scan_at DATE,                        -- МСК-дата полного прохода; NULL — ещё не было
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);
