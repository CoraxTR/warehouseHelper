// Пакет reservewatch — «Контроль резервов заказов»: раз в минуту листает
// заказы в рабочих статусах («Вес подобран», «Обработан», «РефГо», «Курьер»,
// «Перепроверен») с плановой отгрузкой в окне и сверяет резерв позиций
// с их количеством. Позиции без резерва («нужно отложить») и с неверным
// резервом («отложены неверно») уходят уведомлением в чат склада с URL-
// кнопкой на страницу подбора заказа. Владелец таблицы reserve_notices.
package reservewatch

import "errors"

// Kind — вид проблемы резерва заказа (сообщение в чат склада и запись
// reserve_notices; PK — пара order_id + kind).
type Kind string

const (
	// KindMissing — «В заказ нужно отложить»: позиция с quantity > 0 и
	// reserve == 0 (товар не отложен физически).
	KindMissing Kind = "reserve_missing"
	// KindWrong — «позиции отложены неверно»: quantity > 0, reserve != 0,
	// но quantity != reserve (отложено меньше/больше заказанного).
	KindWrong Kind = "reserve_wrong"
)

// ErrNoActiveProblem — проблема резерва не активна (при закрытии записи,
// которой нет: повторный тик после рестарта).
var ErrNoActiveProblem = errors.New("активной проблемы резерва нет")

// Notice — активное уведомление о проблеме резерва (строка reserve_notices).
// Строка живёт, пока проблема активна: позиции исправлены или заказ вышел из
// окна — модуль удаляет сообщение из чата и строку. Вставляется ТОЛЬКО после
// успешной отправки (message_id известен) — сбой между send и insert даёт
// редкий дубль в чате, дедуп по PK на следующем тике его не повторит.
type Notice struct {
	OrderID   string // uuid заказа МС (id, не href)
	Kind      Kind
	MessageID int64 // TG message_id (deleteMessage после выздоровления)
}

// CatalogProduct — товар каталога для сверки резерва: код склада (пусто —
// товар не складской, в проверку не идёт) и тип учёта (весовой — сверка
// в граммах, штучный — по количеству).
type CatalogProduct struct {
	ProductID    string // uuid товара в МС
	InternalCode string // код склада; пусто — товар без кода
	Weighted     bool   // весовой (сверка в граммах) или штучный (по количеству)
}
