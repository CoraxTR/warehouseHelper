package usecase

import (
	"context"
)

// Шов событий стока (stock.SetLotChangeListener): модуль расчёта узнаёт, что
// данные пары изменились вне его тика.

// OnLotsChanged — лоты товара изменились: приёмка увеличила накопленный
// остаток, подбор его уменьшил, со страницы «Сроки» поменяли ручную скидку.
//
// Событие только ОТМЕЧАЕТ товар: свежие оборот и решение он получит в
// ближайшем тике избытка. Внутри нет ни обращений в МС, ни выборок из БД —
// обработчик вызывается из записи остатков, и приёмка на 50 позиций не должна
// ждать сети. Изменения скидок и уведомления о них считает тик по реестру:
// скидку могли поднять и снять несколько раз подряд, сообщать о каждом шаге
// незачем — человеку важно состояние, а не перебор.
func (uc *UseCase) OnLotsChanged(_ context.Context, productID string) error {
	uc.MarkDirty(productID)

	return nil
}

// OnManualDiscountChanged — ручную скидку поставили вручную (шов стока): товар
// пересчитывается СРАЗУ, а не минутным тиком. Иначе свежая ручная ТГ-скидка не
// занимала бы место в окне до следующего тика, и страница «Сроки» держала бы
// пустую правую колонку (решение владельца 29.09.2026: скидка показана сразу).
// MarkDirty оставлен страховкой: если пересчёт не удался, пару догонит тик.
func (uc *UseCase) OnManualDiscountChanged(ctx context.Context, productID string) error {
	if productID == "" {
		return nil
	}
	uc.MarkDirty(productID)

	return uc.RecalcAffected(ctx, uc.now(), []string{productID})
}
