// Объём продаж для добора ТГ-слота из избытка: сколько штук товара надо
// продать, чтобы коэффициент избытка стал строго < 1 у ВСЕХ пар группы, и как
// разложить этот объём по парам (FIFO: сначала ближние сроки).
//
// Зачем: в ТГ-день (вт/чт) слот добирается позициями избытка (§13 черновика), а
// в 16:00 скидка сайта поднимается до плана. Объём — контрольное число для
// рассылки и для вечернего подъёма: менеджер видит, сколько штук должно уйти,
// чтобы избыток по позиции закрылся, и сверяет с ним факт продаж, а не гадает
// «на глаз».
package usecase

import (
	"warehouseHelper/internal/discounts"
)

// SurplusSale — сколько штук пары уходит в продажу по плану добора. Записи
// идут в порядке пар товара (от ближнего срока к дальнему) и складываются ровно
// в объём плана.
type SurplusSale struct {
	Key discounts.LotKey
	Qty int64
}

// SurplusSalePlan — объём продаж X, который снимает избыток у всех пар группы,
// и раскладка X по парам FIFO.
//
// pairs — пары ОДНОГО товара по возрастанию срока, как их отдаёт Evaluate.
// Работаем по группе избытка (непрерывный отрезок помеченных пар, см.
// applySurplusGroup): пара вне группы — не наш случай, её остаток продавать не
// предлагаем. Пары без данных оборота (Rate <= 0, он же HasRate = false) избытка
// иметь не могут и вклада не дают.
//
// Правило: чтобы коэффициент пары стал строго меньше единицы, продать надо
// СТРОГО больше её «лишка» need = CumQty − v×D (для пар с need > 0), поэтому
// вклад пары — floor(need) + 1: при «ровно need» коэффициент равен 1, а это ещё
// избыток. Объём X — максимум вкладов. Одна пара задаёт X, остальные пары
// группы закрываются тем же объёмом: раскладка идёт с ближних сроков, значит
// накопленный остаток каждой следующей пары уменьшается на весь взятый перед
// ней объём (в любом порядке, лишь бы не меньше её вклада).
//
// X ограничен сверху остатком самой группы: продать больше, чем есть, нельзя.
// В обычном случае (перед группой пар нет) это CumQty последней пары группы;
// если впереди остались просроченные пары, их остаток в CumQty входит, но
// продавать его мы не вправе (группа их не берёт) — потому и берём сумму Qty по
// группе. Когда потолок срабатывает, правило «< 1» выполняется настолько,
// насколько позволяет остаток группы.
//
// Возврат: (X, раскладка). Пустой срез, а не nil-панику, когда избытка нет:
// у всех пар группы need <= 0, группа не помечена вовсе или данных оборота нет.
// X отдаём рядом с раскладкой, хотя формально он равен сумме её записей: шаг
// печатает объём контрольным числом, и правило округления (floor + 1) должно
// жить здесь, а не повторяться у вызывающего.
func SurplusSalePlan(pairs []PairState) (int64, []SurplusSale) {
	group := surplusGroup(pairs)
	if len(group) == 0 {
		return 0, nil
	}

	var x, available int64
	for _, p := range group {
		available += p.Qty
		need := surplusNeed(p)
		if need <= 0 {
			continue
		}
		// need > 0, поэтому int64(...) отбрасывает дробную часть ровно как
		// floor. Эпсилон — от копящейся ошибки float: без него need = 5,000…1
		// мог бы посчитаться как 4,999…9 и вклад вышел бы на штуку меньше,
		// оставив коэффициент на единице (то же округление, что в
		// discounts.ExpiryPercent).
		if contribution := int64(need+1e-9) + 1; contribution > x {
			x = contribution
		}
	}
	if x <= 0 {
		return 0, nil
	}
	if x > available {
		x = available
	}

	// Раскладка FIFO: ближний срок забирает весь свой остаток, пока объём не
	// разложен. Нулевые записи не пишем — паре, которой объёма не досталось,
	// в плане делать нечего.
	sales := make([]SurplusSale, 0, len(group))
	left := x
	for _, p := range group {
		if left == 0 {
			break
		}
		take := min(p.Qty, left)
		if take <= 0 {
			continue
		}
		sales = append(sales, SurplusSale{Key: p.Key, Qty: take})
		left -= take
	}

	return x, sales
}

// surplusNeed — «лишек» пары: на сколько штук её накопленный остаток (CumQty,
// включая саму пару) больше того, что успеет продаться за остаток срока (v×D).
// Оборот за день — свойство товара, поэтому у всех пар группы он один.
// Данных оборота нет (Rate <= 0 — то же самое, что HasRate = false, см.
// discounts.SurplusCoeff) или срок вышел (DaysLeft <= 0) → 0: избытка у такой
// пары быть не может, и продавать «по избытку» ей нечего.
func surplusNeed(p PairState) float64 {
	if p.Rate <= 0 || p.DaysLeft <= 0 {
		return 0
	}
	return float64(p.CumQty) - p.Rate*float64(p.DaysLeft)
}

// surplusGroup — пары группы избытка товара: непрерывный отрезок пар, который
// пометил Evaluate (applySurplusGroup). Отрезок может начинаться не с первой
// пары товара: просроченные пары (DaysLeft <= 0) группа не берёт, а они идут
// впереди — по возрастанию срока. Пары за группой избытка не имеют и в план
// добора не входят.
func surplusGroup(pairs []PairState) []PairState {
	start := -1
	for i, p := range pairs {
		if p.SurplusGroup {
			start = i
			break
		}
	}
	if start < 0 {
		return nil
	}
	end := start
	for end < len(pairs) && pairs[end].SurplusGroup {
		end++
	}
	return pairs[start:end]
}
