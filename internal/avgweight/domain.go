// Пакет avgweight — модуль «Средний вес».
//
// Владеет таблицей product_received_weights (веса принятых единиц, граммы):
// модуль приёмки передаёт сюда единичные веса всех кусков по позициям
// (RecordWeights), модуль пишет их поштучно, оставляет последние N записей
// на товар (FIFO по id) и пересчитывает по ним средний вес. Результат
// передаёт каталогу (products.average_weight) и вики — через их юзкейсы,
// чужие таблицы не пишет (границы по владельцу записи).
package avgweight

// WeightRow — единичный вес принятого куска (граммы).
type WeightRow struct {
	ProductID string
	WeightG   int64
}
