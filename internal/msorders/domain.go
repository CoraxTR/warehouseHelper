// Пакет msorders — доменные типы модуля «Заказы МойСклад» (internal/msorders):
// раздел подбора заказов и журнал подбора (таблица order_picking).
//
// Своих сущностей в МС у модуля нет — заказы живут в МойСклад; здесь только
// то, что модуль хранит сам: журнал подобранных единиц с датами выработки и
// срока годности (нужен, потому что МС дат подобранных кусков не хранит).
package msorders

import "time"

// PickingUnit — одна подобранная единица товара (строка журнала подбора):
// весовой товар — один кусок, штучный — одна штука. Единица появляется в
// журнале при отправке подбора и уходит из него, когда товар возвращается в
// «Сроки» (переподбор, расформирование).
type PickingUnit struct {
	OrderID      string     // uuid заказа МС (заказы в МС — внешний ключ логический)
	PositionID   string     // id позиции заказа; у смёрженной группы — живая позиция
	InternalCode string     // код склада (assortment.code) — 8 цифр
	ProductID    string     // uuid товара каталога склада (products.id); пусто — товара нет в каталоге
	ProductName  string     // название товара на момент подбора (снимок)
	Weighted     bool       // весовой (true) или штучный (false)
	WeightKg     float64    // вес единицы: весовые — кг куска, штучные — 1
	ProducedOn   *time.Time // дата выработки (UTC-полночь); nil — не известна
	BestBefore   time.Time  // срок годности (UTC-полночь)
}

// PickingReplace — замена журнала по позициям заказа: строки перечисленных
// позиций удаляются, вместо них пишутся Units. Так пишется подбор и
// переподбор (набираем строку с нуля); добор строки дозаписывает единицы
// (AppendOrderPicking).
type PickingReplace struct {
	OrderID     string
	PositionIDs []string
	Units       []PickingUnit
}

// PickingReturn — вернувшиеся в «Сроки» единицы одного товара: из журнала
// заказа убирается ровно Count строк, совпавших по коду склада, сроку годности
// и весу (весовой кусок возвращается один и тот же, штучных может вернуться
// несколько). Возврат без совпадений — не ошибка: строки могли быть записаны
// до появления журнала.
type PickingReturn struct {
	OrderID      string
	InternalCode string
	BestBefore   time.Time
	WeightKg     float64
	Count        int
}
