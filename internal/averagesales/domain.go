// Пакет averagesales — модуль «Средние продажи».
//
// Владеет таблицами product_weekly_turnover и product_monthly_turnover:
// хранит продажи по позициям за неделю/месяц (в штуках) и по требованию
// отдаёт средние продажи за окно (месячные 12 / недельные 5). Продажи
// берутся из отчёта прибыльности МойСклад (report/profit/byproduct)
// строго через msclient (воркерпул с рейт-лимитом).
//
// ВНИМАНИЕ (для будущих интеграций с этим модулем): у товара без единых
// продаж (ни одного интервала — новый товар, продаж ещё не было) средние
// продажи отсутствуют: AverageSales возвращает (nil, nil). Такие товары
// неотличимы от товаров, которые никогда не продавались, и модули-
// потребители (расчёт заказов/скидок и т.п.) ОБЯЗАНЫ уметь их пропускать.
// При проектировании интеграции — уточнить у владельца обработку этой
// ситуации (дефолт/пропуск/ошибка).
package averagesales

import "time"

// TurnoverRow — продажи товара за период (месяц или неделю), в штуках.
// Для весовых товаров (uom кг/г/т): (кг продаж − кг возвратов) / средний вес
// штуки; для штучных — количество как есть. Возврат «задним числом» даёт
// отрицательный qty — хранится честно.
type TurnoverRow struct {
	ProductID   string
	PeriodStart time.Time // понедельник недели или 1-е число месяца
	Qty         float64   // штуки: весовые (sell−ret)/avg_weight, штучные как есть
}

// TurnoverProduct — срез каталога для модуля оборотов (читается через
// интерфейс ProductReader, реализует каталог — владелец products).
type TurnoverProduct struct {
	ID            string
	UOM           string   // "кг", "шт", ... — весовой ⇔ кг/г/т
	AverageWeight *float64 // кг/шт, NULL = не задан
	TrackWeekly   bool
	FolderID      string // id папки МС (products.folder_id); "" — без группы
}
