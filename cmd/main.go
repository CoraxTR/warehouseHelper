package main

import (
	"errors"
	"log/slog"
	"os"

	"warehouseHelper/app"
	"warehouseHelper/internal/config"
	"warehouseHelper/internal/logging"
)

func main() {
	config.LoadEnv()
	logging.Setup()

	a := app.New()

	if err := a.Run(); err != nil {
		// Остановка «с замечаниями» — не отказ: часть работы не доработала до
		// таймаутов, но процесс остановлен штатно и ресурсы закрыты. Выход 0,
		// иначе менеджер служб (NSSM) запишет это как падение и перезапустит
		// службу — а перезапуск ничего не исправит, работа повторится сама.
		if errors.Is(err, app.ErrStopIncomplete) {
			slog.Warn("процесс остановлен с замечаниями (часть работы не доработала)", "error", err)

			return
		}

		// А это именно отказ запуска (занятый порт и т.п.) — выход 1.
		slog.Error("ошибка запуска сервера", "error", err)
		os.Exit(1)
	}

	// Run возвращает nil только после штатной остановки (Ctrl+C/SIGTERM):
	// ресурсы закрыты, фоновые задачи остановлены — выходим с кодом 0.
	slog.Info("процесс завершён штатно")

	//TODO: Добавить автосоздание отгрузок в МС при выгрузке заказов
	//TODO: Дать через страницу доступ к поиску всех заказов в базе
	//TODO: Добавить автопроверку и автоподьём базы, если её нет
	//TODO: Шаблоны перевести на go:embed (сейчас грузятся относительными путями "../internal/delivery/web/templates/*" и работают только из cmd/): go test пакета internal/delivery/http паникует в init, запуск из другого каталога тоже. Embed даст тесты роутера (регресс на дубли паттернов) и запуск откуда угодно
}
